import { before, describe, it } from 'node:test';
import assert from 'node:assert/strict';

import { moscowMoment } from '../backend/demo/time.js';
import { createExternalTriage } from '../backend/planner/triage.js';
import { loadCatalog, __resetCatalogCache } from '../backend/privacy/catalog.js';
import { makeTestPipeline, TEST_SESSION } from './helpers.js';

const NOW = moscowMoment('2026-10-12', '12:00');
let catalog;
before(async () => {
  process.env.DEMO_DATA = 'on';
  delete process.env.PUBLIC_CLINICS;
  __resetCatalogCache();
  catalog = await loadCatalog();
});

/*
 * Внешний триаж вызывается только для неочевидной жалобы: к последней реплике добавляется
 * такая фраза — худший случай, запрос гарантированно уходит наружу.
 */
const PAD = ', и ещё неделю плохо вижу вдаль, перед глазами мушки';
const run = async (turns, { pad = true } = {}) => {
  const bodies = [];
  const fetchImpl = async (url, init) => {
    bodies.push(JSON.parse(init.body));
    return { ok: true, status: 200, headers: { get: () => null }, json: async () => ({ choices: [{ message: { content: JSON.stringify({ status: 'specialist', specialties: ['therapist'], question: null, options: null }) } }], usage: {} }) };
  };
  const triage = createExternalTriage({ apiKey: 'k', url: 'https://llm.example.test/v1/chat/completions', model: 'm', fetchImpl });
  const { pipeline } = makeTestPipeline({ catalog, triage, booking: { enabled: true, now: () => NOW } });
  const result = await pipeline.handle({ messages: turns.map((content, i) => ({ role: 'user', content: pad && i === turns.length - 1 ? `${content}${PAD}` : content })), sessionId: TEST_SESSION });
  const user = bodies.at(-1)?.messages.find((m) => m.role === 'user')?.content || '';
  return { sent: user.toLowerCase().replace(/ё/gu, 'е'), result };
};
const norm = (v) => v.toLowerCase().replace(/ё/gu, 'е');

// [название, реплики, медицинские фрагменты (дословно), ПДн, которых быть не должно].
// Имена не совпадают с врачами демо-каталога: иначе запрос — обращение к врачу, без триажа.
const CASES = [
  ['симптом, интенсивность, локализация', ['Меня зовут Алсу Гарифуллина, ноющая боль в правом колене 6 из 10, сильнее при спуске по лестнице'], ['ноющая боль в правом колене 6 из 10', 'сильнее при спуске по лестнице'], ['алсу', 'гарифуллин']],
  ['длительность и порядок событий', ['Пишет Ниязбек Фатыхов: сначала поднялась температура 38.7, через два дня появилась сыпь на животе, сейчас третий день'], ['сначала поднялась температура 38.7', 'через два дня появилась сыпь на животе', 'третий день'], ['ниязбек', 'фатыхов']],
  ['отрицания', ['я Эльвира Каримова, тошноты нет, рвоты не было, но болит справа под ребрами после жирного'], ['тошноты нет', 'рвоты не было', 'болит справа под ребрами после жирного'], ['эльвира', 'каримов']],
  ['лекарство и доза', ['Это Ильдар Нуриев, пью метформин 1000 мг два раза в день и бисопролол 5 мг утром, кружится голова'], ['метформин 1000 мг два раза в день', 'бисопролол 5 мг утром', 'кружится голова'], ['ильдар', 'нуриев']],
  ['витамин и единицы', ['Гузель Ахметова, пью витамин D 2000 МЕ, ферритин 9 нг/мл, выпадают волосы'], ['витамин d 2000 ме', 'ферритин 9 нг/мл', 'выпадают волосы'], ['гузель', 'ахметов']],
  ['анализы', ['Меня зовут Ринат Сафин, ТТГ 6.2, Т4 свободный 11, холестерин 7.4 ммоль/л, устаю'], ['ттг 6.2', 'т4 свободный 11', 'холестерин 7.4 ммоль/л'], ['ринат', 'сафин']],
  ['давление и пульс', ['Лилия Закирова: давление 165/100 мм рт. ст., пульс 98, шумит в ушах по утрам'], ['давление 165/100 мм рт. ст.', 'пульс 98', 'шумит в ушах по утрам'], ['лилия', 'закиров']],
  ['беременность', ['Я Диляра Хасанова, беременность 24 недели, отекают ноги и болит голова к вечеру'], ['беременность 24 недели', 'отекают ноги', 'болит голова к вечеру'], ['диляра', 'хасанов']],
  ['эпонимы', ['Пишет Ярослав Бурмистров, у отца болезнь Бехтерева, у меня по Нечипоренко лейкоциты 4000, ноет поясница'], ['болезнь бехтерева', 'по нечипоренко лейкоциты 4000', 'ноет поясница'], ['ярослав', 'бурмистров']],
  ['ребенок и возраст', ['Сыну Тимуру 4 года, температура 39.1 со вчерашнего вечера, не ест, жаропонижающее помогает на два часа'], ['4 года', 'температура 39.1 со вчерашнего вечера', 'не ест', 'жаропонижающее помогает на два часа'], ['тимур']],
  ['ФИО в скобках рядом с лекарством', ['Подпись: [Таисия Квятковская], левотироксин 75 мкг, ТТГ 4,8 мМЕ/л, мерзну'], ['левотироксин 75 мкг', 'ттг 4,8 мме/л', 'мерзну'], ['таисия', 'квятковск']],
  ['многоходовой анамнез', ['Меня зовут Айгуль Шакирова.', 'Месяц назад болела ангиной, лечилась амоксициллином 500 мг.', 'Теперь неделю болят колени и отекают, температуры нет.'], ['месяц назад болела ангиной', 'амоксициллином 500 мг', 'неделю болят колени и отекают', 'температуры нет'], ['айгуль', 'шакиров']],
];

describe('Медицинский смысл после Privacy Layer', () => {
  for (const [name, turns, keep, gone] of CASES) {
    it(name, async () => {
      const { sent } = await run(turns);
      assert.ok(sent.length > 0, 'жалоба не ушла во внешний триаж');
      const lost = keep.filter((fragment) => !sent.includes(norm(fragment)));
      assert.deepEqual(lost, [], `потеряны фрагменты; ушло: ${sent}`);
      for (const value of gone) assert.ok(!sent.includes(value), `«${value}» ушло наружу: ${sent}`);
    });
  }

  it('признаки экстренного состояния не уходят наружу и получают локальный ответ 103/112', async () => {
    for (const text of ['Меня зовут Марат Гиниятуллин, резко онемела правая рука и перекосило лицо', 'Это Ольга Петрова, задыхаюсь, губы синеют']) {
      const { sent, result } = await run([text], { pad: false });
      assert.equal(sent, '', `ушло во внешний триаж: ${text}`);
      assert.match(JSON.stringify(result.action), /103|112/u, text);
    }
  });
});
