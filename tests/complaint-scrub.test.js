/*
 * Модели-триажу уходят только слова о самочувствии: без места, времени, цены,
 * страховки, работы и меток вместо имён.
 */
import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import { hasSensitiveCondition, minimizeComplaint } from '../backend/privacy/complaintScrub.js';

describe('Жалоба для модели: только о самочувствии', () => {
  it('длинная фраза: остаётся жалоба, условия записи убраны', () => {
    const text = minimizeComplaint('Я нахожусь в Казани, рядом с площадью Тукая. Последние несколько дней у меня закладывает правое ухо, не знаю, к какому врачу обратиться. Подбери подходящего специалиста на ближайшие два дня, желательно после 17:30, стоимостью до 2 500 ₽ и не дальше 20 минут на машине.');
    assert.match(text, /закладывает правое ухо/);
    assert.doesNotMatch(text, /казан|тукая|17:30|2 500|машин|подбери/iu);
  });

  it('работа, школа и район не уходят, жалоба остаётся', () => {
    const text = minimizeComplaint('Я @PERSON_A, завуч школы № 12 в Авиастроительном районе, у сына @PERSON_B 7 лет эпилепсия, лечусь у доктора @PERSON_C, болит голова и тошнит');
    assert.doesNotMatch(text, /@|завуч|школ|№|авиастроит/iu);
    assert.match(text, /эпилепсия/);
    assert.match(text, /болит голова/);
    assert.match(text, /тошнит/);
  });

  for (const phrase of ['болит живот вверху и изжога', 'да, есть температура', 'справа', 'со вчерашнего дня', 'не знаю', 'после еды', 'в районе сердца колет', 'болит около уха', 'пять минут', 'температура до 38']) {
    it(`фраза о самочувствии не меняется: «${phrase}»`, () => {
      assert.equal(minimizeComplaint(phrase), phrase);
    });
  }

  for (const phrase of ['по ДМС', 'до 3000 рублей', 'завтра после 18:00', 'рядом с Кремлём', 'живу на Азино', 'работаю в компании', 'не дальше 20 минут', 'найди врача']) {
    it(`без жалобы передавать нечего: «${phrase}»`, () => {
      assert.equal(minimizeComplaint(phrase), '');
    });
  }

  it('метка в начале реплики не оставляет лишней запятой', () => {
    assert.equal(minimizeComplaint('@PERSON_A, справа внизу, со вчерашнего дня'), 'справа внизу, со вчерашнего дня');
  });

  it('особые диагнозы не передаются даже без имени', () => {
    for (const phrase of ['у мужа ВИЧ', 'вич инфекция', 'лечусь от гепатита', 'был аборт, болит живот', 'нужен психиатр', 'алкоголизм у отца']) {
      assert.equal(hasSensitiveCondition(phrase), true, phrase);
    }
    for (const phrase of ['болит живот', 'кашель с мокротой', 'вичуга', 'спидометр']) {
      assert.equal(hasSensitiveCondition(phrase), false, phrase);
    }
  });
});
