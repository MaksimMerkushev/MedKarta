/** Короткая справка, добавляемая к запросу: перечислимые подсказки Gateway. */
export const buildHintBlock = (hints) => {
  if (!hints || typeof hints !== 'object') {
    return '';
  }

  const lines = [];
  if (hints.specialties?.length) {
    lines.push(`Профили из локального анализа: ${hints.specialties.join(', ')}.`);
  }
  if (hints.districts?.length) {
    lines.push(`Упомянутые районы: ${hints.districts.join(', ')}.`);
  }
  if (hints.constraints && Object.keys(hints.constraints).length > 0) {
    lines.push(`Ограничения из текста: ${JSON.stringify(hints.constraints)}.`);
  }
  if (hints.isChild) {
    lines.push('Приём детский.');
  }
  if (hints.medicalTextWithheld) {
    lines.push('Описание жалоб удалено локально и тебе не передаётся.');
  }
  if (hints.textWithheld) {
    lines.push('Текст запроса заменён описанием: исходные слова не передаются.');
  }

  return lines.join(' ');
};
