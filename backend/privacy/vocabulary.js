const WORDS = new Set();
const STEMS = new Set();

const addEntry = (entry) => {
  const raw = entry.trim();
  if (!raw) return;
  if (raw.endsWith('*')) {
    const stem = normalizeRu(raw.slice(0, -1));
    if (stem.length >= 3) STEMS.add(stem);
    return;
  }
  const word = normalizeRu(raw);
  if (word) WORDS.add(word);
};

for (const entry of `${BASE} ${SYSTEM_WORDS}`.split(/\s+/)) addEntry(entry);

/*
 * Публичные топонимы и специальности из справочника.
 * Прилагательные («Чистопольская», «Детский») получают основу: их пишут
 * в разных падежах. Названия-родительные («Баумана», «Николая Ершова»)
 * добавляются как есть: так их и пишут, а основа «бауман*» пропускала бы
 * фамилию «Бауманом».
 */
const ADJECTIVE_TAIL = /(?:ая|яя|ий|ый|ой|ое|ее|ые|ие)$/u;

export const addPublicPhrase = (phrase) => {
  for (const part of normalizeRu(String(phrase || '')).split(/[^\p{L}]+/u)) {
    if (part.length < 2) continue;
    if (ADJECTIVE_TAIL.test(part) && part.length >= 6) {
      STEMS.add(part.slice(0, -2));
    }
    WORDS.add(part);
  }
};

/** Тип улицы в адресе справочника: всё, что рядом с ним, — название улицы. */
const STREET_IN_ADDRESS =
  /(?:^|,\s*)(?:(?:ул\.|улица|проспект|пр-т|пр\.|переулок|пер\.|бульвар|б-р|тракт|шоссе|площадь|пл\.)\s*([^,]+)|([^,]+?)\s(?:улица|проспект|тракт|шоссе|переулок|бульвар|площадь))(?=,|$)/giu;

/** Названия улиц из адресов справочника. Экспортируется для gateway. */
export const extractStreetNames = (address) => {
  const names = [];
  const regex = new RegExp(STREET_IN_ADDRESS.source, 'giu');
  let match;
  while ((match = regex.exec(String(address || ''))) !== null) {
    const name = (match[1] || match[2] || '').trim();
    if (name && name.length <= 48 && !/\d{3,}/u.test(name)) names.push(name);
  }
  return names;
};

