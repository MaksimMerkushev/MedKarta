/**
 * Подключает справочник: специальности, районы, улицы и типы учреждений.
 * Вызывается один раз при создании gateway; повторный вызов безвреден.
 *
 * @param {{doctors?: Array, clinics?: Array, specialties?: Array, districts?: Array}} catalog
 */
/*
 * Улицы НЕ попадают в общий словарь: «улица Нурсултана Назарбаева» внесла
 * бы в него имя «Нурсултан», и «запишите Нурсултана …» ушло бы наружу.
 * Название улицы разрешается только целиком и только в «уличном»
 * контексте (см. stripStreetMentions).
 */
const STREET_ADJECTIVE_STEMS = new Set();

const addStreet = (street) => {
  const normalized = normalizeRu(street);
  if (!normalized) return;
  KNOWN_STREETS.add(normalized);
  // «на Фучика», «на Ершова»: улицу с именем пишут по одной фамилии.
  const last = normalized.split(' ').pop();
  if (last && last.length >= 4) KNOWN_STREETS.add(last);
  // «Чистопольская» → «на Чистопольской»: прилагательное меняет окончание.
  if (!normalized.includes(' ') && ADJECTIVE_TAIL.test(normalized) && normalized.length >= 6) {
    STREET_ADJECTIVE_STEMS.add(normalized.slice(0, -2));
  }
};

for (const street of [...MAJOR_STREETS, ...KNOWN_PLACES]) addStreet(street);

export const registerCatalogVocabulary = (catalog = {}) => {
  for (const label of catalog.specialties || []) addPublicPhrase(label);
  for (const district of catalog.districts || []) addPublicPhrase(district);
  const records = [...(catalog.clinics || []), ...(catalog.doctors || [])];
  for (const record of records) {
    if (record?.facilityType) addPublicPhrase(record.facilityType);
    for (const street of extractStreetNames(record?.address)) addStreet(street);
  }
};

/** Известна ли улица (в той форме, в какой она записана в справочнике). */
export const isKnownStreet = (text) => {
  const normalized = normalizeRu(text);
  if (KNOWN_STREETS.has(normalized)) return true;
  if (normalized.includes(' ') || normalized.length < 6) return false;
  return /(?:ая|ой|ую|ий|ый|ого|ому|ом|ем)$/u.test(normalized)
    && (STREET_ADJECTIVE_STEMS.has(normalized.replace(/(?:ого|ому)$/u, '').replace(/(?:ая|ой|ую|ий|ый|ом|ем)$/u, '')));
};

/* Слово перед названием, по которому ясно, что это улица или место. */
const STREET_CUE_WORDS = new Set([
  'на', 'по', 'с', 'со', 'от', 'до', 'ул', 'улица', 'улице', 'улицу', 'улицы', 'улицей', 'проспект', 'проспекте',
  'проспекта', 'пр', 'переулок', 'переулке', 'бульвар', 'бульваре', 'тракт', 'тракте', 'площадь', 'площади',
  'шоссе', 'возле', 'около', 'метро', 'район', 'районе', 'напротив', 'угол', 'углу', 'станция', 'станции',
].map((word) => normalizeRu(word)));
const STREET_TYPE_AFTER = /^(?:улиц|проспект|тракт|шоссе|бульвар|переул|площад)/u;
/* Номер дома после улицы делает её адресом — такой текст не отправляется. */
const HOUSE_NUMBER_AFTER = /^\s*[,.]?\s*(?:д\.?|дом|№)?\s*\d/iu;

/**
 * Заменяет пробелами упоминания известных улиц и мест в «уличном»
 * контексте, если за ними не следует номер дома.
 */
const stripStreetMentions = (text) => {
  const words = [];
  const regex = /[\p{L}\p{M}]+(?:-[\p{L}\p{M}]+)*/gu;
  let match;
  while ((match = regex.exec(text)) !== null) {
    words.push({ raw: match[0], start: match.index, end: match.index + match[0].length });
  }

  let out = text;
  for (let i = 0; i < words.length; i += 1) {
    for (let size = Math.min(3, words.length - i); size >= 1; size -= 1) {
      const last = words[i + size - 1];
      const between = text.slice(words[i].start, last.end);
      if (/[^\p{L}\p{M}\s-]/u.test(between)) continue;
      if (!isKnownStreet(between)) continue;

      const previous = words[i - 1];
      const next = words[i + size];
      const cued = (previous && STREET_CUE_WORDS.has(normalizeRu(previous.raw))
        && /^\s+$/u.test(text.slice(previous.end, words[i].start)))
        || (next && STREET_TYPE_AFTER.test(normalizeRu(next.raw)));
      if (!cued || HOUSE_NUMBER_AFTER.test(text.slice(last.end))) continue;

      out = out.slice(0, words[i].start) + ' '.repeat(last.end - words[i].start) + out.slice(last.end);
      i += size - 1;
      break;
    }
  }
  return out;
};

/*
 * Улица, названная в честь человека: «на Ямашева», «на Николая Ершова»,
 * «Оренбургский тракт». Детектор ФИО и резолвер видят здесь фамилию или
 * врача; раньше такой запрос либо не уходил наружу, либо планировщик
 * получал «стоматология на @PERSON_A». Улицей считается только известное
 * название и только рядом с «уличным» словом. Используется и gateway,
 * и выходным предохранителем planner/client.js — иначе второй отклонял бы
 * то, что пропустил первый.
 */
const STREET_CUE = /(?:^|[^\p{L}])(?:на|по|с|со|от|до|ул\.?|улиц\p{L}*|проспект\p{L}*|пр\.|пр-т|пр-кт|переул\p{L}*|бульвар\p{L}*|тракт\p{L}*|площад\p{L}*|шоссе|возле|около|рядом\s+с|недалеко\s+от|район\p{L}*|напротив|угол\p{L}*|метро)\s+(?:\p{Lu}\p{Ll}+\s+)?$/iu;
const STREET_AFTER = /^\s+(?:улиц|проспект|пр-т|тракт|шоссе|бульвар|переул|площад)/iu;
const STREET_KINDS = new Set([ENTITY_KIND.PERSON, ENTITY_KIND.DOCTOR, ENTITY_KIND.CLINIC]);

export const isStreetMention = (content, entity) => {
  if (!STREET_KINDS.has(entity.kind) || entity.matcher === 'person.selfIntro' || entity.detector === 'person.selfIntro') {
    return false;
  }
  const slice = content.slice(entity.start, entity.end).trim();
  const before = content.slice(Math.max(0, entity.start - 40), entity.start);
  const after = content.slice(entity.end, entity.end + 16);
  const previousWord = before.match(/(\p{Lu}\p{Ll}+)\s+$/u)?.[1];
  const known = isKnownStreet(slice) || (previousWord && isKnownStreet(`${previousWord} ${slice}`));
  return Boolean(known) && (STREET_CUE.test(before) || STREET_AFTER.test(after));
};

/** Известные публичные места, найденные в тексте, — для синтезированной реплики. */
export const findKnownPlaces = (text) => {
  const normalized = ` ${normalizeRu(text)} `;
  return KNOWN_PLACES.filter((place) => normalized.includes(` ${normalizeRu(place)} `));
};

/** Слово из словаря? Проверка по форме и по «основа + окончание». */
export const isAllowedWord = (word) => {
  const normalized = normalizeRu(word);
  if (!normalized) return true;
  if (WORDS.has(normalized)) return true;
  for (let cut = normalized.length; cut >= 3 && normalized.length - cut <= 4; cut -= 1) {
    if (STEMS.has(normalized.slice(0, cut)) && ENDINGS.has(normalized.slice(cut))) {
      return true;
    }
  }
  return false;
};

/*
 * Символы, допустимые между словами. Всё прочее — «буквы» других систем,
 * буквенные символы (Ⓐ, 🇦), управляющие — означает отказ: такой текст
 * пытаются провести мимо проверки слов.
 */
const ALLOWED_SEPARATOR = /^[\s.,!?;:()"'«»„“”‘’\-–—/%+=№#*<>[\]{}_~…·•]$|^\p{Extended_Pictographic}$|^(?:\u200d|\ufe0e|\ufe0f)$|^[\u{1f3fb}-\u{1f3ff}]$/u;

/** Время «18:00» — не номер: ни на что личное не указывает. */
const TIME = /(?<![\d:.,])(?:[01]?\d|2[0-3]):[0-5]\d(?![\d:.,])/gu;

export const MAX_DIGITS = 5;
export const MAX_DIGIT_RUN = 3;

/**
 * Проверяет набор исходящих реплик целиком.
 *
 * Цифры считаются по всем репликам вместе: телефон, разложенный на три
 * сообщения по четыре цифры, по отдельности проходил бы.
 *
 * @param {string[]} texts исходящие тексты
 * @param {Iterable<string>} tokens выданные в этом запросе токены (@DOCTOR_A…)
 * @returns {{ok: boolean, reason: string|null}} причина — вид нарушения,
 *          без самих слов: её можно логировать.
 */
export const checkClosedVocabulary = (texts, tokens = []) => {
  const issued = [...new Set(tokens)].filter(Boolean).sort((left, right) => right.length - left.length);
  let digits = 0;

  for (const original of texts) {
    let text = String(original || '').normalize('NFKC');
    for (const token of issued) {
      text = text.split(token).join(' ');
    }
    text = text.replace(TIME, ' ');

    for (const char of text) {
      if (/\p{N}/u.test(char)) {
        digits += 1;
        continue;
      }
      if (/[\p{L}\p{M}]/u.test(char)) continue;
      if (!ALLOWED_SEPARATOR.test(char)) {
        return { ok: false, reason: 'symbol' };
      }
    }
    if (digits > MAX_DIGITS) return { ok: false, reason: 'digits' };

    for (const run of text.match(/\p{N}+/gu) || []) {
      if (run.length > MAX_DIGIT_RUN) return { ok: false, reason: 'digits' };
    }

    // Остатки токенов («@») и выдуманные токены («@HOME_IVAN») — не наши.
    if (/@/u.test(text)) return { ok: false, reason: 'token' };

    for (const word of stripStreetMentions(text).match(/[\p{L}\p{M}]+/gu) || []) {
      if (!isAllowedWord(word)) {
        return { ok: false, reason: 'word' };
      }
    }
  }

  return { ok: true, reason: null };
};
