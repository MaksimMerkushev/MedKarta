// Единицы измерения и обозначения доз: «1000 МЕ», «4,8 мМЕ/л», «12 нг/мл».
const UNITS = ['мг', 'мкг', 'мл', 'г', 'кг', 'л', 'ме', 'мме', 'ед', 'ммоль', 'мкмоль', 'нмоль', 'пмоль', 'нг', 'пг', 'мм', 'рт', 'ст', 'см', 'уд', 'мин', 'таб', 'табл', 'капс'];
// Слова при названии лекарства или анализа во фрагменте модели: «Цитрамон 2 таблетки в день».
const DOSAGE_CONTEXT = /^(?:таблетк\p{L}*|капсул\p{L}*|капл\p{L}*|укол\p{L}*|раз[а]?|день|дня|дней|сутки|суток|утром|вечером|ночью|днем|натощак|после|до|еды|по|в|во|на|не|и|или|с|без|уже|пью|пила|пил|принимаю|принимала|принимал|назначил[аи]?|назначили|курс\p{L}*|недел\p{L}*|месяц\p{L}*|помога\p{L}*|помог\p{L}*|дозировк\p{L}*|доз\p{L}*|половин\p{L}*|четверт\p{L}*)$/u;

const WORDS = new Set([...DRUGS, ...LABS, ...SYMPTOMS, ...UNITS]);
const EPONYM = new RegExp(`^(?:${EPONYM_STEMS.join('|')})(?:а|у|ом|е|ым|ой|ого|ому|ским|ская|ский|ского)?$`, 'u');
const norm = (word) => String(word || '').toLowerCase().replace(/ё/gu, 'е').replace(/^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu, '');

// Падежные формы: «амоксициллином», «метформина», «ангиной» — сравнение по основе от четырёх букв.
const CASE_ENDING = /(?:ами|ями|ом|ем|ой|ей|ым|им|ах|ях|ам|ям|а|я|у|ю|е|ы|и)$/u;
const stemOf = (w) => {
  const stem = w.replace(CASE_ENDING, '');
  return stem.length >= 4 ? stem : w;
};
const STEMS = new Set([...DRUGS, ...LABS, ...SYMPTOMS].map(stemOf));

/** Медицинское слово (лекарство, анализ, симптом, эпоним) — маскировать нельзя. */
export const isMedicalWord = (word) => {
  const w = norm(word);
  return WORDS.has(w) || EPONYM.test(w) || WORDS.has(w.replace(/-/gu, '')) || (w.length >= 5 && STEMS.has(stemOf(w)));
};

/** Все слова фрагмента медицинские (и есть хотя бы одно слово). */
export const isMedicalPhrase = (text) => {
  const words = String(text || '').match(/[\p{L}\p{N}-]+/gu) || [];
  return words.length > 0 && words.every((w) => isMedicalWord(w) || /^\d+(?:[.,]\d+)?$/u.test(w));
};

/** Во фрагменте есть название лекарства, анализа или эпоним — это медицинская фраза, а не имя. */
const DRUG_STEMS = new Set([...DRUGS, ...LABS].map(stemOf));
export const mentionsMedicalName = (text) => (String(text || '').match(/[\p{L}\p{N}-]+/gu) || []).some((w) => {
  const n = norm(w);
  return DRUGS.includes(n) || DRUGS.includes(n.replace(/-/gu, '')) || LABS.includes(n) || EPONYM.test(n) || (n.length >= 5 && DRUG_STEMS.has(stemOf(n)));
});

/** Аббревиатуры анализов, исследований и единиц (для правила «слово заглавными — организация»). */
export const MEDICAL_ABBREVIATION = (word) => LABS.includes(norm(word)) || UNITS.includes(norm(word)) || /^м?ме\/л$/u.test(norm(word));

/** Слово дозировки или приёма рядом с названием лекарства — не имя. */
export const isDosageWord = (word) => DOSAGE_CONTEXT.test(norm(word)) || /^\d+(?:[.,]\d+)?$/u.test(norm(word));

// Витамин с буквой и доза с единицей — смысл, который маскировать нельзя: «витамин D», «1000 МЕ».
const VITAMIN = /витамин\p{L}*\s+[A-Za-zА-Яа-яЁё]\d{0,2}(?![\p{L}\p{N}])/giu;
const DOSE = /(?<![\d.,])\d+(?:[.,]\d+)?\s*(?:ммоль\/л|мкмоль\/л|нмоль\/л|пмоль\/л|мг\/л|г\/л|нг\/мл|пг\/мл|мме\/л|ме\/л|ед\/л|мм\s*рт\.?\s*ст\.?|мкг|мг|мл|мме|ме|ед|г|%)(?![\p{L}])/giu;

/** Диапазоны медицинского смысла, которые не входят ни в одну маску (кроме номеров документов и контактов). */
export const protectedMedicalRanges = (text) => [VITAMIN, DOSE].flatMap((re) => [...String(text).matchAll(new RegExp(re.source, re.flags))].map((m) => ({ start: m.index, end: m.index + m[0].length })));
