/*
 * Падежные формы строятся по окончанию. Правила грубые, но для поиска этого
 * достаточно: лишняя форма не мешает, а пропущенная — утечка.
 */
const MALE_ENDINGS = ['', 'а', 'у', 'ом', 'е', 'ым', 'ем', 'я', 'ю'];
const FEMALE_A_ENDINGS = ['а', 'ы', 'и', 'е', 'у', 'ой', 'ою', 'ей'];
const FEMALE_YA_ENDINGS = ['я', 'и', 'ю', 'ей', 'е'];
const IYA_ENDINGS = ['ия', 'ии', 'ию', 'ией'];

const formsOf = (name) => {
  const base = normalizeRu(name);
  const forms = new Set([base]);
  if (base.endsWith('ия')) {
    const stem = base.slice(0, -2);
    for (const ending of IYA_ENDINGS) forms.add(stem + ending);
  } else if (base.endsWith('ья')) {
    const stem = base.slice(0, -2);
    for (const ending of ['ья', 'ьи', 'ью', 'ьей', 'ье']) forms.add(stem + ending);
  } else if (base.endsWith('я')) {
    const stem = base.slice(0, -1);
    for (const ending of FEMALE_YA_ENDINGS) forms.add(stem + ending);
  } else if (base.endsWith('а')) {
    const stem = base.slice(0, -1);
    for (const ending of FEMALE_A_ENDINGS) forms.add(stem + ending);
  } else if (base.endsWith('й')) {
    const stem = base.slice(0, -1);
    for (const ending of ['й', 'я', 'ю', 'ем', 'е']) forms.add(stem + ending);
  } else if (base.endsWith('ь')) {
    const stem = base.slice(0, -1);
    for (const ending of ['ь', 'я', 'ю', 'ем', 'е']) forms.add(stem + ending);
  } else {
    for (const ending of MALE_ENDINGS) forms.add(base + ending);
  }
  return forms;
};

const FORMS = new Set();
for (const name of [...MALE, ...FEMALE]) {
  for (const form of formsOf(name)) FORMS.add(form);
}

/** Является ли слово (в любом регистре и падеже) личным именем из словаря. */
export const isFirstName = (word) => FORMS.has(normalizeRu(word));

export const FIRST_NAME_FORMS_COUNT = FORMS.size;
